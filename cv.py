# Function to format and output experiences
def format_experience(experience):
   output = ''
   date = experience.get('date', '')
   roles = experience.get('role', '')
   if isinstance(roles, list):
      roles = ', '.join(roles)
   company = experience.get('company', '')
   output += f"`{date}` <span style=\"font-size:1.2em;\">**{roles}**</span>, {company}\n"
   description = experience.get('description', '')
   output += f"- {description}\n"

   # Projects
   projects = experience.get('projects', [])
   for project in projects:
      title = project.get('title', '')
      desc = project.get('description', '')
      url = project.get('url', '')
      output += f"- **{title}**: {desc}"
      if url:
         output += f", [Link: {title}]({url})"
      output += "\n"

   # Skills
   skills = set()
   extra_skills = experience.get('extra_skills', [])
   if isinstance(extra_skills, list):
      skills.update(extra_skills)
   for project in projects:
      project_skills = project.get('skills', [])
      skills.update(project_skills)
   if skills:
      skill_list = ', '.join(sorted(skills))
      output += f"- **Skills**: {skill_list}\n"

   output += "\n"  # Add a newline for separation
   return output


# Main function to iterate over experiences
def main():
   print("## Experience\n")
   experiences = d.get('experience', [])
   for experience in experiences:
      exp_output = format_experience(experience)
      print(exp_output)


if __name__ == "__main__":
   main()
