from pprint import pprint
# print all values that are in the key or nested keys "skills" or other "skills"
def get_skills(d, results=None):
   results = [] if not results else results
   for k, v in d.items():
      if k == "skills" or k == "extra_skills":
         results.extend(v)
      elif isinstance(v, dict):
         results = get_skills(v, results=results)
      elif isinstance(v, list):
         for item in v:
            if isinstance(item, dict):
               results = get_skills(item, results=results)
   return list(set(results))

skills = get_skills(d)

